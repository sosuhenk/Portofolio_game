    setTitles()
    {
        // Font (Anton, converted from resources/fonts/Anton-Regular.ttf with scripts/convertFont.mjs)
        const font = new FontLoader().parse(antonTypeface)

        // Layout (matches the previous name footprint: height 1.39, depth 0.43, row center y -9.48)
        const title = {}
        title.text = 'RAY JOSEPH'
        title.capHeight = 1.39
        title.depth = 0.43
        title.tracking = 0.15
        title.wordSpacing = 0.55
        title.x = - 0.1
        title.y = - 9.481
        title.size = title.capHeight / (antonTypeface.capHeight / antonTypeface.resolution)

        // Create one geometry per glyph
        const items = []

        for(const character of title.text)
        {
            if(character === ' ')
            {
                items.push({ width: title.wordSpacing - title.tracking * 2 })
                continue
            }

            const geometry = new TextGeometry(character, { font, size: title.size, depth: title.depth, curveSegments: 8, bevelEnabled: false })

            // Stand the glyph up (text lies in the XY plane and extrudes along Z)
            geometry.rotateX(Math.PI * 0.5)
            geometry.computeBoundingBox()

            const bounds = geometry.boundingBox
            const width = bounds.max.x - bounds.min.x
            const height = bounds.max.z - bounds.min.z
            const centerZ = (bounds.min.z + bounds.max.z) * 0.5

            // Center on X and depth, keep the bottom on the floor
            geometry.translate(- (bounds.min.x + bounds.max.x) * 0.5, - (bounds.min.y + bounds.max.y) * 0.5, 0)

            items.push({ geometry, width, height, centerZ })
        }

        // Single row layout
        let totalWidth = title.tracking * (items.length - 1)
        for(const item of items)
        {
            totalWidth += item.width
        }

        let cursor = title.x - totalWidth * 0.5

        for(const item of items)
        {
            const centerX = cursor + item.width * 0.5
            cursor += item.width + title.tracking

            if(!item.geometry)
            {
                continue
            }

            // Base
            const base = new THREE.Object3D()

            const mesh = new THREE.Mesh(item.geometry)
            mesh.name = 'shadeWhite'
            base.add(mesh)

            // Collision (box + center, same convention as the other models)
            const collision = new THREE.Object3D()

            const center = new THREE.Object3D()
            center.name = 'center'
            collision.add(center)

            const box = new THREE.Mesh(new THREE.BoxGeometry(1, 1, 1))
            box.name = 'Cube'
            box.scale.set(item.width, title.depth, item.height)
            box.position.set(0, 0, item.centerZ)
            collision.add(box)

            // Add
            this.objects.add({
                base,
                collision,
                offset: new THREE.Vector3(centerX, title.y, 0),
                rotation: new THREE.Euler(0, 0, 0),
                shadow: { sizeX: 1.5, sizeY: 1.5, offsetZ: - 0.6, alpha: 0.4 },
                mass: 1.5,
                soundName: 'brick'
            })
        }

        // Words lying flat on the floor (same spirit as the previous "creative"/"dev" models)
        const words = [
            { text: 'KREATIF', x: 6.0, y: - 10.3, rotation: 0.25, capHeight: 0.76, depth: 0.33, sleep: false, shadow: { sizeX: 5, sizeY: 1.5, offsetZ: - 0.6, alpha: 0.3 } },
            { text: 'DEV', x: 4.0, y: - 11.9, rotation: - 0.087, capHeight: 0.75, depth: 0.33, shadow: { sizeX: 2.5, sizeY: 1.5, offsetZ: - 0.6, alpha: 0.3 } }
        ]

        for(const word of words)
        {
            const size = word.capHeight / (antonTypeface.capHeight / antonTypeface.resolution)
            const geometry = new TextGeometry(word.text, { font, size, depth: word.depth, curveSegments: 8, bevelEnabled: false })
            geometry.computeBoundingBox()

            const bounds = geometry.boundingBox
            geometry.translate(- (bounds.min.x + bounds.max.x) * 0.5, - (bounds.min.y + bounds.max.y) * 0.5, 0)

            const width = bounds.max.x - bounds.min.x
            const height = bounds.max.y - bounds.min.y

            // Base
            const base = new THREE.Object3D()

            const mesh = new THREE.Mesh(geometry)
            mesh.name = 'shadeWhite'
            base.add(mesh)

            // Collision (box + center)
            const collision = new THREE.Object3D()

            const center = new THREE.Object3D()
            center.name = 'center'
            collision.add(center)

            const box = new THREE.Mesh(new THREE.BoxGeometry(1, 1, 1))
            box.name = 'Cube'
            box.scale.set(width, height, word.depth)
            box.position.set(0, 0, word.depth * 0.5)
            collision.add(box)

            // Add
            this.objects.add({
                base,
                collision,
                offset: new THREE.Vector3(word.x, word.y, 0),
                rotation: new THREE.Euler(0, 0, word.rotation),
                shadow: word.shadow,
                mass: 1.5,
                sleep: word.sleep,
                soundName: 'brick'
            })
        }
    }

